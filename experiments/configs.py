def get_run(run_id: str) -> RunSpec:
    key = run_id.upper()
    if key not in EXPERIMENTS:
        valid = ", ".join(sorted(EXPERIMENTS))
        raise KeyError(f"Unknown run id {run_id!r}. Valid run ids: {valid}")
    return EXPERIMENTS[key]


def iter_runs(priority: Optional[str] = None) -> Iterable[RunSpec]:
    runs = EXPERIMENTS.values()
    if priority:
        priority = priority.upper()
        runs = [run for run in runs if run.priority == priority]
    return sorted(runs, key=lambda run: run.run_id)
